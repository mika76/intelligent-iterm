#!/bin/sh
# Installs the ACP adapter and an iTerm2 AutoLaunch launcher for the panel.
#   ./install.sh            install / update
#   ./install.sh uninstall  remove the AutoLaunch launcher
set -eu

REPO="$(cd "$(dirname "$0")" && pwd)"
AUTOLAUNCH="$HOME/Library/Application Support/iTerm2/Scripts/AutoLaunch"
LAUNCHER="$AUTOLAUNCH/intelligent_iterm_panel.py"

if [ "${1:-}" = "uninstall" ]; then
  rm -f "$LAUNCHER"
  echo "Removed $LAUNCHER (restart iTerm2 or stop the script from the Scripts menu)."
  exit 0
fi

command -v npm >/dev/null || { echo "npm not found; install Node.js >= 22 first." >&2; exit 1; }
node -e 'process.exit(+process.versions.node.split(".")[0] >= 22 ? 0 : 1)' \
  || { echo "Node.js >= 22 is required (found $(node -v))." >&2; exit 1; }
command -v claude >/dev/null || echo "warning: 'claude' not on PATH; the adapter will use its bundled CLI." >&2

echo "Installing the Claude Code ACP adapter…"
(cd "$REPO" && npm ci --silent)

mkdir -p "$AUTOLAUNCH"
cat > "$LAUNCHER" <<EOF
# Launcher generated by $REPO/install.sh — runs the Claude side panel.
import sys
sys.path.insert(0, "$REPO")
from intelligent_iterm.main import run
run()
EOF
echo "Wrote $LAUNCHER"

if ! ls -d "$HOME/Library/Application Support/iTerm2/iterm2env"* >/dev/null 2>&1; then
  echo
  echo "NOTE: iTerm2's Python runtime isn't installed yet."
  echo "      In iTerm2: Scripts > Manage > Install Python Runtime."
fi
echo
echo "Checking the setup…"
if command -v python3 >/dev/null; then
  (cd "$REPO" && python3 -m intelligent_iterm.doctor) || true
fi
echo
echo "Next: in iTerm2 run Scripts > AutoLaunch > intelligent_iterm_panel.py (or restart iTerm2),"
echo "      then View > Toolbelt > Claude, and View > Toolbelt > Show Toolbelt."
